//add function
//explicit return
const add= (a,b)=>{
    return a+b;
}
console.log(add(2,3));

//implicit return
const add1=(a,b)=>a+b;
console.log(add1(2,3));

//square function
//explicit return
const square=(n)=>{
    return n*n
}
console.log(square(2));

//implicit return
const square1=(n)=>n*n;
console.log(square1(3));




